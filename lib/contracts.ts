export function buildLegalDocuments(): LegalDocumentDefinition[] {
  const now = "2026-05-11";
  return legalDocumentTypes.map(([type, title]) => ({
    type,
    title,
    version: "1.0.0",
    status: "PUBLISHED",
    issuedAt: now,
    body:
      type === "TERMS_AND_CONDITIONS"
        ? termsSections
        : type === "EQUIPMENT_RENTAL_CONTRACT"
          ? rentalContractSections
          : [
              `${title} وثيقة تشغيلية ضمن ${brand.arabicName} قابلة للتوليد كمسودة PDF مع حقول توقيع وقبول رقمي ومرفقات.`,
              ...protectionClauses.slice(0, 5),
              legalDisclaimer
            ]
  }));
}

export function getLegalDocument(type: string) {
  return buildLegalDocuments().find((document) => document.type === type) ?? buildLegalDocuments()[0];
}

export function buildContractDraft(type: string) {
  const document = getLegalDocument(type);
  return {
    title: document.title,
    version: document.version,
    sections: document.type === "EQUIPMENT_RENTAL_CONTRACT" ? rentalContractSections : document.body,
    protectionClauses,
    disclaimer: legalDisclaimer
  };
}

export function listContractDrafts() {
  return buildLegalDocuments().map((document) => buildContractDraft(document.type));
}
