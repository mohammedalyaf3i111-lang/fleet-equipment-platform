// Generate content for other cities by adapting Riyadh content
function generateCityEquipmentContent(city: CityData, equipment: string): EquipmentCityContent {
  const riydhContent = CITY_EQUIPMENT_DATA.riyadh[equipment];
  if (!riydhContent) return { intro: "", whyHere: [], priceRange: "", tips: [], faqs: [] };

  return {
    ...riydhContent,
    intro: riydhContent.intro.replace("الرياض", city.arabicName),
    whyHere: riydhContent.whyHere.map(w => w.replace("الرياض", city.arabicName)),
    faqs: riydhContent.faqs.map(faq => ({
      q: faq.q.replace("الرياض", city.arabicName),
      a: faq.a.replace("الرياض", city.arabicName)
    }))
  };
}

export function getCityEquipmentContent(citySlug: string, equipmentSlug: string): EquipmentCityContent | null {
  const city = SAUDI_CITIES.find(c => c.slug === citySlug);
  if (!city) return null;

  if (CITY_EQUIPMENT_DATA[citySlug]?.[equipmentSlug]) {
    return CITY_EQUIPMENT_DATA[citySlug][equipmentSlug];
  }

  return generateCityEquipmentContent(city, equipmentSlug);
}

export function getCity(slug: string): CityData | undefined {
  return SAUDI_CITIES.find(c => c.slug === slug);
}

